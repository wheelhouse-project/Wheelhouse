def M(name, old, new, *expect):
    return dict(name=name, service=SERVICE, test_file=tuple(SEL),
                file=CONTROLLER, old=old, new=new, expect=list(expect))


def L(*lines):
    """Join source lines; each argument is one line without its newline."""
    return "\n".join(lines) + "\n"


def block_mutations(prefix, block, specs):
    """One mutation for each spec: a line of the block becomes ``pass`` (or
    the given text), so a mutation never deletes a block's only statement.

    spec = (line index, tag, expected test names, replacement line or None)
    """
    result = []
    for index, tag, expect, replacement in specs:
        lines = list(block)
        indent = lines[index][: len(lines[index]) - len(lines[index].lstrip())]
        lines[index] = replacement if replacement is not None else indent + "pass"
        result.append(M(f"{prefix}-{tag}", L(*block), L(*lines), *expect))
    return result


