"""Mutation gate for the Logic-process training-word controller
(wh-first-sound-lost.23, acceptance items 10, 13, 16 to 18, 20 to 22 and 26).

Run it from services/wheelhouse with the service's own interpreter, never
while a test suite runs in the same worktree (the gate rewrites the source
that suite imports):

    .venv/Scripts/python.exe tests/mutation_gate_lead_word_app_controller.py
    .venv/Scripts/python.exe tests/mutation_gate_lead_word_app_controller.py --check
    .venv/Scripts/python.exe tests/mutation_gate_lead_word_app_controller.py playback

The runner is the shared one (stt_providers/shared/tests/
mutation_gate_runner.py, reached through mutation_gate_exclusive_speaker). A
bare word on the command line selects every mutation whose name contains it.
``--check`` verifies that every pattern matches exactly once and that every
mutant compiles, without running a test.

The target is ``speech/lead_word_controller.py`` only: the screens, the
request IDs, each command, the playback hold (the 300 ms tail, the 60000 ms
limit, the 45 s hold timer, both directions of each boundary), the release
paths, the timeouts and the state message. The wiring in main.py, gui.py, the
WebSocket manager, the state manager and the voice pattern has its own gate
(mutation_gate_lead_word_app_wiring.py).

Each mutation names the tests that must fail for it to count as caught.
Pattern-not-found, an ambiguous pattern, a mutant that does not compile, a
timeout, a suite-timeout abort and a missing expected test name are reported
as errors, never as a verdict.

NOT MUTATED, each with the reason (see NOT_MUTATED at the bottom): the
statements that repeat what another statement already guarantees.
"""

