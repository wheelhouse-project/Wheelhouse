"""Mutation gate for the app-side wiring of the training-word window
(wh-first-sound-lost.23, acceptance items 10, 12, 19, 22 and 27).

Run it from services/wheelhouse with the service's own interpreter, never
while a test suite runs in the same worktree (the gate rewrites the sources
that suite imports):

    .venv/Scripts/python.exe tests/mutation_gate_lead_word_app_wiring.py
    .venv/Scripts/python.exe tests/mutation_gate_lead_word_app_wiring.py --check
    .venv/Scripts/python.exe tests/mutation_gate_lead_word_app_wiring.py websocket

The runner is the shared one (stt_providers/shared/tests/
mutation_gate_runner.py, reached through mutation_gate_exclusive_speaker). A
bare word on the command line selects every mutation whose name contains it.
``--check`` verifies that every pattern matches exactly once and that every
Python mutant compiles, without running a test; the expected catcher names are
checked against the collected tests when a sweep starts.

WHAT THIS GATE DEFENDS (everything except the two new files, which have their
own gates: mutation_gate_lead_word_controller.py and ..._dialog.py):

  gui.py                    the Logic-to-GUI messages (open_lead_word,
                            lw_state, lw_play_go), the one-window rule, the
                            commands that leave the GUI, the environment the
                            window gets, the foreground request, the tray and
                            floating-button menu entries, and the connection
                            of the Settings window button
  main.py                   the ten lw_* action names, their handler map, the
                            lazily built controller and its provider channel
                            (active client only, named tasks, the hold that
                            runs before the sound, the failures it contains)
  integrations/websocket_manager.py
                            the lead_word_result route (active client only),
                            the capability declaration (only a literal true),
                            the reset when a stream starts and ends
  state_manager.py          the transcription hold and its release
  settings_window_dialog.py the 'Training word...' button
  speech/actions.py, speech/action_catalog.py, speech/config/patterns.toml
                            the spoken command: the action, its catalog entry
                            and the whole-utterance pattern row

The push-to-talk rule of acceptance item 12 lives in the provider's
recorder (stage G1) and is not in this gate.

Every mutation names the tests that must fail for it to count as caught.
Pattern-not-found, an ambiguous pattern, a mutant that does not compile, a
timeout, a suite-timeout abort and a missing expected test name are reported
as errors, never as a verdict.

NOT MUTATED, each with the reason (see NOT_MUTATED at the bottom).
"""

