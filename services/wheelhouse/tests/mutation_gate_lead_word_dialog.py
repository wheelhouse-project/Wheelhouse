"""Mutation gate for the 'Your training word' window (wh-first-sound-lost.23,
acceptance items 20, 21, 13, 17, 18, 22, 23, 25 and 26).

Run it from services/wheelhouse with the service's own interpreter, never
while a test suite runs in the same worktree (the gate rewrites the source
that suite imports):

    .venv/Scripts/python.exe tests/mutation_gate_lead_word_dialog.py
    .venv/Scripts/python.exe tests/mutation_gate_lead_word_dialog.py --check
    .venv/Scripts/python.exe tests/mutation_gate_lead_word_dialog.py keep-text

The runner is the shared one (stt_providers/shared/tests/
mutation_gate_runner.py, reached through mutation_gate_exclusive_speaker). A
bare word on the command line selects every mutation whose name contains it.
``--check`` verifies that every pattern matches exactly once and that every
mutant compiles, without running a test.

The target is ``lead_word_dialog.py`` only. Every mutation changes one
behaviour a user can see or a command a button sends: a window state with its
buttons and texts, a button command, the Keep text, the playback rules, the
close rules, the accessible names. Each mutation names the tests that must
fail for it to count as caught. Pattern-not-found, an ambiguous pattern, a
mutant that does not compile, a timeout, a suite-timeout abort and a missing
expected test name are reported as errors, never as a verdict.

NOT MUTATED, each with the reason (see NOT_MUTATED at the bottom): appearance
that no acceptance item names, wording nothing asserts, and mutations that
change no behaviour.
"""

